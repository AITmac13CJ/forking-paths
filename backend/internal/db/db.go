package db

import (
	"context"
	_ "embed"
	"fmt"
	"time"

	"github.com/jackc/pgx/v5/pgxpool"
)

//go:embed schema.sql
var schemaSQL string

func Connect(url string) (*pgxpool.Pool, error) {
	cfg, err := pgxpool.ParseConfig(url)
	if err != nil {
		return nil, fmt.Errorf("解析数据库地址: %w", err)
	}
	cfg.MaxConns = 8

	var last error
	for i := 0; i < 30; i++ {
		ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
		pool, err := pgxpool.NewWithConfig(ctx, cfg)
		if err == nil {
			err = pool.Ping(ctx)
		}
		cancel()
		if err == nil {
			return pool, nil
		}
		if pool != nil {
			pool.Close()
		}
		last = err
		time.Sleep(time.Second)
	}
	return nil, fmt.Errorf("连接数据库失败: %w", last)
}

func Migrate(ctx context.Context, pool *pgxpool.Pool) error {
	_, err := pool.Exec(ctx, schemaSQL)
	if err != nil {
		return fmt.Errorf("初始化数据表: %w", err)
	}
	if err := migrateAccounts(ctx, pool); err != nil {
		return err
	}
	return nil
}

func migrateAccounts(ctx context.Context, pool *pgxpool.Pool) error {
	_, err := pool.Exec(ctx, `
		DO $$
		BEGIN
			IF EXISTS (
				SELECT 1
				FROM pg_constraint c
				JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
				WHERE c.conrelid = 'platform_accounts'::regclass
					AND c.contype = 'p'
					AND a.attname = 'provider'
					AND array_length(c.conkey, 1) = 1
			) THEN
				ALTER TABLE platform_accounts DROP CONSTRAINT platform_accounts_pkey;
			END IF;
		END $$;
		ALTER TABLE platform_accounts ADD COLUMN IF NOT EXISTS id INT GENERATED BY DEFAULT AS IDENTITY;
		DO $$
		BEGIN
			IF NOT EXISTS (
				SELECT 1 FROM pg_constraint
				WHERE conrelid = 'platform_accounts'::regclass AND contype = 'p'
			) THEN
				ALTER TABLE platform_accounts ADD PRIMARY KEY (id);
			END IF;
		END $$;
		CREATE UNIQUE INDEX IF NOT EXISTS platform_accounts_user_provider_uidx
			ON platform_accounts (user_id, provider);
	`)
	if err != nil {
		return fmt.Errorf("整理平台账号: %w", err)
	}
	return nil
}
